#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TEST_TMP="$(mktemp -d)"
FAKE_BIN="$TEST_TMP/bin"
HANDOFF_ENV_PATH="$TEST_TMP/base-release-handoff.env"
CALLS_LOG="$TEST_TMP/calls.log"
DEPLOYER_ENV_LOG="$TEST_TMP/deployer-env.log"
SEED_ENV_LOG="$TEST_TMP/seed-env.log"
export TEST_TMP HANDOFF_ENV_PATH CALLS_LOG DEPLOYER_ENV_LOG SEED_ENV_LOG

cleanup() {
  rm -rf "$TEST_TMP"
}
trap cleanup EXIT

mkdir -p "$FAKE_BIN"

cat > "$FAKE_BIN/forge" <<'EOF'
#!/usr/bin/env bash
set -euo pipefail

echo "$*" >> "$CALLS_LOG"

if [[ "$*" == *"DeployInfrastructure.s.sol:DeployInfrastructure"* ]]; then
  cat <<OUT
  HANDOFF:REGISTRY=0x1000000000000000000000000000000000000001
  HANDOFF:CREATOR_REGISTRY=0x1000000000000000000000000000000000000001
  HANDOFF:CREATOR_FACTORY=0x1000000000000000000000000000000000000002
  HANDOFF:LOTTERY_MANAGER=0x1000000000000000000000000000000000000003
  HANDOFF:CREATOR_LOTTERY_MANAGER=0x1000000000000000000000000000000000000003
  HANDOFF:VRF_CONSUMER=0x1000000000000000000000000000000000000004
  HANDOFF:CREATOR_VRF_CONSUMER=0x1000000000000000000000000000000000000004
  HANDOFF:VAULT_ACTIVATION_BATCHER=0x1000000000000000000000000000000000000005
  HANDOFF:SOLANA_BRIDGE_ADAPTER=0x1000000000000000000000000000000000000006
  HANDOFF:BASE_SHARED_GLOBAL_OUTPUT_PATH=${BASE_SHARED_GLOBAL_OUTPUT_PATH:-}
OUT
  exit 0
fi

if [[ "$*" == *"DeployBaseMainnetDeployer.s.sol:DeployBaseMainnetDeployer"* ]]; then
  {
    echo "DEPLOYMENT_EPOCH_TAG=${DEPLOYMENT_EPOCH_TAG:-}"
    echo "REGISTRY=${REGISTRY:-}"
    echo "VAULT_ACTIVATION_BATCHER=${VAULT_ACTIVATION_BATCHER:-}"
    echo "LOTTERY_MANAGER=${LOTTERY_MANAGER:-}"
    echo "SOLANA_BRIDGE_ADAPTER=${SOLANA_BRIDGE_ADAPTER:-}"
    echo "CONFIGURE_SOLANA=${CONFIGURE_SOLANA:-}"
    echo "CONFIGURE_OVAULT_RUNTIME=${CONFIGURE_OVAULT_RUNTIME:-}"
  } >> "$DEPLOYER_ENV_LOG"
  cat <<'OUT'
  HANDOFF:UNIVERSAL_BYTECODE_STORE=0x2000000000000000000000000000000000000001
  HANDOFF:UNIVERSAL_CREATE2_DEPLOYER=0x2000000000000000000000000000000000000002
  HANDOFF:UNIVERSAL_CREATE2_FROM_STORE=0x2000000000000000000000000000000000000002
  HANDOFF:DEPLOYMENT_BATCHER=0x2000000000000000000000000000000000000003
  HANDOFF:CREATOR_VAULT_BATCHER=0x2000000000000000000000000000000000000003
  HANDOFF:CREATOR_VAULT_BATCHER_AUTO_HANDOFF=0x2000000000000000000000000000000000000003
OUT
  exit 0
fi

if [[ "$*" == *"ConfigureDeploymentBatcherSolana.s.sol:ConfigureDeploymentBatcherSolana"* ]]; then
  touch "$TEST_TMP/solana-configured"
  exit 0
fi

if [[ "$*" == *"SeedUniversalBytecodeStore.s.sol:SeedUniversalBytecodeStore"* ]]; then
  {
    echo "UNIVERSAL_BYTECODE_STORE=${UNIVERSAL_BYTECODE_STORE:-}"
  } >> "$SEED_ENV_LOG"
  touch "$TEST_TMP/seeded"
  exit 0
fi

exit 0
EOF

cat > "$FAKE_BIN/cargo" <<'EOF'
#!/usr/bin/env bash
set -euo pipefail

echo "cargo $*" >> "$CALLS_LOG"
exit 0
EOF

chmod +x "$FAKE_BIN/forge" "$FAKE_BIN/cargo"

PATH="$FAKE_BIN:$PATH" \
PRIVATE_KEY="0xabc123" \
BASE_RPC_URL="https://base.invalid" \
SOLANA_DESTINATION="0x1111111111111111111111111111111111111111111111111111111111111111" \
CONFIGURE_SOLANA="1" \
CONFIGURE_OVAULT_RUNTIME="1" \
BASE_SHARED_GLOBAL_OUTPUT_PATH="$TEST_TMP/base-shared-global.json" \
BASE_RELEASE_HANDOFF_ENV_PATH="$HANDOFF_ENV_PATH" \
bash "$ROOT_DIR/script/deploy-base-full-release.sh"

rg '^DEPLOYMENT_EPOCH_TAG=v1\.8\.2$' "$HANDOFF_ENV_PATH" >/dev/null
rg '^REGISTRY=0x1000000000000000000000000000000000000001$' "$HANDOFF_ENV_PATH" >/dev/null
rg '^LOTTERY_MANAGER=0x1000000000000000000000000000000000000003$' "$HANDOFF_ENV_PATH" >/dev/null
rg '^VAULT_ACTIVATION_BATCHER=0x1000000000000000000000000000000000000005$' "$HANDOFF_ENV_PATH" >/dev/null
rg '^SOLANA_BRIDGE_ADAPTER=0x1000000000000000000000000000000000000006$' "$HANDOFF_ENV_PATH" >/dev/null
rg '^UNIVERSAL_BYTECODE_STORE=0x2000000000000000000000000000000000000001$' "$HANDOFF_ENV_PATH" >/dev/null
rg '^UNIVERSAL_CREATE2_FROM_STORE=0x2000000000000000000000000000000000000002$' "$HANDOFF_ENV_PATH" >/dev/null
rg '^DEPLOYMENT_BATCHER=0x2000000000000000000000000000000000000003$' "$HANDOFF_ENV_PATH" >/dev/null

rg '^DEPLOYMENT_EPOCH_TAG=v1\.8\.2$' "$DEPLOYER_ENV_LOG" >/dev/null
rg '^REGISTRY=0x1000000000000000000000000000000000000001$' "$DEPLOYER_ENV_LOG" >/dev/null
rg '^VAULT_ACTIVATION_BATCHER=0x1000000000000000000000000000000000000005$' "$DEPLOYER_ENV_LOG" >/dev/null
rg '^LOTTERY_MANAGER=0x1000000000000000000000000000000000000003$' "$DEPLOYER_ENV_LOG" >/dev/null
rg '^SOLANA_BRIDGE_ADAPTER=0x1000000000000000000000000000000000000006$' "$DEPLOYER_ENV_LOG" >/dev/null
rg '^CONFIGURE_SOLANA=0$' "$DEPLOYER_ENV_LOG" >/dev/null
rg '^CONFIGURE_OVAULT_RUNTIME=0$' "$DEPLOYER_ENV_LOG" >/dev/null

rg '^UNIVERSAL_BYTECODE_STORE=0x2000000000000000000000000000000000000001$' "$SEED_ENV_LOG" >/dev/null

rg 'DeployInfrastructure\.s\.sol:DeployInfrastructure' "$CALLS_LOG" >/dev/null
rg 'DeployBaseMainnetDeployer\.s\.sol:DeployBaseMainnetDeployer' "$CALLS_LOG" >/dev/null
rg 'SeedUniversalBytecodeStore\.s\.sol:SeedUniversalBytecodeStore' "$CALLS_LOG" >/dev/null
if rg 'ConfigureDeploymentBatcherSolana\.s\.sol:ConfigureDeploymentBatcherSolana' "$CALLS_LOG" >/dev/null; then
  echo "Expected treasury-only Solana batcher config to remain opt-in" >&2
  exit 1
fi
if rg '^cargo ' "$CALLS_LOG" >/dev/null; then
  echo "Expected no cargo manifest generation in full release path" >&2
  exit 1
fi

if [ -f "$TEST_TMP/solana-configured" ]; then
  echo "Expected no default treasury-only Solana config run" >&2
  exit 1
fi
test -f "$TEST_TMP/seeded"

echo "base full release wrapper handoff test passed"
